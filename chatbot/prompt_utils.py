# 정규 표현식 패턴
# -----------------------------------------------------------------------------
RADIUS_PATTERN = re.compile(r"(\d+(?:\.\d+)?)\s*(km|킬로미터|m|미터)", re.IGNORECASE)
MORE_RESULTS_PATTERN = re.compile(r"(다른|또|더|없어|추가|더 보여)")
LOCATION_KEYWORD_PATTERN = re.compile(r"장소|지역")

# -----------------------------------------------------------------------------
# 함수 정의
# -----------------------------------------------------------------------------
def extract_radius(message: str) -> int:
    """
    메시지에서 반경 정보를 추출하여 미터 단위로 반환합니다.
    예: '2km' -> 2000, '300m' -> 300
    찾지 못하면 기본값 3000을 반환합니다.
    """
    match = RADIUS_PATTERN.search(message)
    if match:
        value = float(match.group(1))
        unit = match.group(2).lower()
        return int(value * 1000) if 'k' in unit else int(value)
    return 3000


def get_system_prompt(
    topic: str,
    user: Any,
    liked_tags: Optional[List[str]] = None,
    disliked_tags: Optional[List[str]] = None,
    allergies: Optional[List[str]] = None
) -> str:
    """
    주제와 사용자 선호/알레르기 정보를 기반으로 시스템 프롬프트 문자열을 생성합니다.

    Args:
        topic: 대화 주제 ("비음식" 또는 그 외)
        user: Django User 객체 (현재 사용자를 전달받지만 내부 로직에서는 사용되지 않음)
        liked_tags: 사용자가 선호하는 식재료/태그 리스트
        disliked_tags: 사용자가 기피하는 식재료/태그 리스트
        allergies: 사용자의 알레르기 리스트

    Returns:
        시스템 메시지로 사용할 문자열
    """
    if topic == "비음식":
        return NON_FOOD_PROMPT

    # 연속 대화 힌트
    contextual_hint = (
        "\n※ 이 질문은 이전 대화와 연속된 내용일 수 있습니다."
        " 맥락을 고려해서 답변해 주세요.\n"
    )

    # 사용자 정보 추가
    extra = ""
    if allergies or liked_tags or disliked_tags:
        extra = (
            f"\n- 알레르기: {allergies or []}"
            f"\n- 선호 태그: {liked_tags or []}"
            f"\n- 기피 태그: {disliked_tags or []}"
        )

    return BASE_INTRO + contextual_hint + extra
